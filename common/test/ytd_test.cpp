// Host test for common/ytd.cpp.
//
// We hand-build a flat payload with system + graphics memory
// concatenated, then run ytd::open and check the recovered Texture
// metadata matches what we put in. The data pointer values use the
// resource convention (0x50000000 | sys_off, 0x60000000 | gfx_off)
// so the parser's resolve_pointer gets exercised on both sides.
//
//   * full_mip_size: a few algebra vectors to pin the mip-chain sum.
//   * open() with ONE texture: validate every field, including a
//     name resolved from a null-terminated string in system memory
//     and pixel data sliced from graphics memory.
//   * open() with TWO textures: pointer-array walk works for more
//     than one entry, textures stay independent, find() returns the
//     right one case-insensitively.
//   * Error paths: bad dictionary (count/hashes-count mismatch),
//     pointer out of range, too-small payload.

#include "../ytd.h"

#include <cstdint>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

namespace {

int failures = 0;

#define CHECK(cond, msg)                                                   \
    do {                                                                   \
        if (!(cond)) {                                                     \
            ++failures;                                                    \
            std::fprintf(stderr, "FAIL: %s (%s:%d)\n", msg, __FILE__,      \
                         __LINE__);                                        \
        }                                                                  \
    } while (0)

constexpr std::uint64_t kSystemBase   = 0x50000000ull;
constexpr std::uint64_t kGraphicsBase = 0x60000000ull;

void put_u16(std::uint8_t* buf, std::size_t off, std::uint16_t x) {
    buf[off + 0] = static_cast<std::uint8_t>(x & 0xff);
    buf[off + 1] = static_cast<std::uint8_t>((x >> 8) & 0xff);
}
void put_u32(std::uint8_t* buf, std::size_t off, std::uint32_t x) {
    buf[off + 0] = static_cast<std::uint8_t>( x        & 0xff);
    buf[off + 1] = static_cast<std::uint8_t>((x >>  8) & 0xff);
    buf[off + 2] = static_cast<std::uint8_t>((x >> 16) & 0xff);
    buf[off + 3] = static_cast<std::uint8_t>((x >> 24) & 0xff);
}
void put_u64(std::uint8_t* buf, std::size_t off, std::uint64_t x) {
    for (int i = 0; i < 8; ++i) {
        buf[off + i] = static_cast<std::uint8_t>(x & 0xff);
        x >>= 8;
    }
}

// A hand-built YTD payload containing a configurable number of
// textures. All offsets are chosen so the test can assert them
// directly without parsing them back out of the generated bytes.
struct Fixture {
    std::vector<std::uint8_t> payload;
    std::size_t system_size   = 0;
    std::size_t graphics_size = 0;
};

struct FakeTexture {
    std::string   name;
    std::uint32_t name_hash;
    std::uint16_t width;
    std::uint16_t height;
    std::uint16_t depth;
    std::uint16_t stride;
    std::uint32_t format;
    std::uint8_t  levels;
    std::vector<std::uint8_t> full_data;  // mip 0 + mip 1 + ...
};

Fixture make_fixture(const std::vector<FakeTexture>& fakes) {
    // System layout:
    //   +0x00  TextureDictionary (64 bytes)
    //   +0x40  name_hashes array (count * 4 bytes)
    //   next   texture-pointer array (count * 8 bytes)
    //   next   N Texture structs (count * 144 bytes, 16-byte aligned)
    //   next   name strings (null-terminated, concatenated)
    // Graphics layout:
    //   +0x00  texture 0 pixel data (full mip chain)
    //   next   texture 1 pixel data
    //   ...
    const std::size_t count = fakes.size();
    const std::size_t name_hashes_off = 0x40;
    const std::size_t name_hashes_bytes = count * 4;
    std::size_t tex_ptrs_off = name_hashes_off + name_hashes_bytes;
    // 8-byte align tex_ptrs_off for the uint64 array.
    tex_ptrs_off = (tex_ptrs_off + 7u) & ~std::size_t{7};
    const std::size_t tex_ptrs_bytes = count * 8;
    std::size_t textures_off = tex_ptrs_off + tex_ptrs_bytes;
    // 16-byte align texture structs for cosmetic cleanliness.
    textures_off = (textures_off + 15u) & ~std::size_t{15};
    const std::size_t textures_bytes = count * 144;
    std::size_t names_off = textures_off + textures_bytes;

    // Build a names blob first so we can record each name's offset.
    std::vector<std::size_t> name_offs(count, 0);
    std::vector<std::uint8_t> names_blob;
    for (std::size_t i = 0; i < count; ++i) {
        name_offs[i] = names_off + names_blob.size();
        names_blob.insert(names_blob.end(),
                          fakes[i].name.begin(), fakes[i].name.end());
        names_blob.push_back(0);
    }
    std::size_t system_size = names_off + names_blob.size();
    // Pad system memory to 16 bytes for cleanliness.
    system_size = (system_size + 15u) & ~std::size_t{15};

    // Graphics memory: one pixel-data region per texture, 16-byte
    // aligned so each DataPointer lands on a nice boundary.
    std::vector<std::size_t> data_offs(count, 0);
    std::size_t graphics_size = 0;
    for (std::size_t i = 0; i < count; ++i) {
        data_offs[i] = graphics_size;
        graphics_size += fakes[i].full_data.size();
        graphics_size = (graphics_size + 15u) & ~std::size_t{15};
    }

    Fixture f;
    f.system_size   = system_size;
    f.graphics_size = graphics_size;
    f.payload.assign(system_size + graphics_size, 0);
    std::uint8_t* sys = f.payload.data();
    std::uint8_t* gfx = f.payload.data() + system_size;

    // TextureDictionary header (64 bytes):
    //   0x00..0x1F opaque unknowns (leave as zero; parser ignores them)
    //   0x20..0x2F TextureNameHashes list
    //   0x30..0x3F Textures list
    put_u64(sys, 0x20, kSystemBase | name_hashes_off);
    put_u16(sys, 0x28, static_cast<std::uint16_t>(count));
    put_u16(sys, 0x2A, static_cast<std::uint16_t>(count));

    put_u64(sys, 0x30, kSystemBase | tex_ptrs_off);
    put_u16(sys, 0x38, static_cast<std::uint16_t>(count));
    put_u16(sys, 0x3A, static_cast<std::uint16_t>(count));

    // name_hashes array.
    for (std::size_t i = 0; i < count; ++i) {
        put_u32(sys, name_hashes_off + i * 4, fakes[i].name_hash);
    }

    // texture-pointer array.
    for (std::size_t i = 0; i < count; ++i) {
        std::uint64_t ptr = kSystemBase | (textures_off + i * 144);
        put_u64(sys, tex_ptrs_off + i * 8, ptr);
    }

    // Texture structs.
    for (std::size_t i = 0; i < count; ++i) {
        std::size_t t_off = textures_off + i * 144;
        // NamePointer at +0x28.
        put_u64(sys, t_off + 0x28, kSystemBase | name_offs[i]);
        // Width/Height/Depth/Stride at +0x50..+0x57.
        put_u16(sys, t_off + 0x50, fakes[i].width);
        put_u16(sys, t_off + 0x52, fakes[i].height);
        put_u16(sys, t_off + 0x54, fakes[i].depth);
        put_u16(sys, t_off + 0x56, fakes[i].stride);
        // Format at +0x58.
        put_u32(sys, t_off + 0x58, fakes[i].format);
        // Levels at +0x5D.
        sys[t_off + 0x5D] = fakes[i].levels;
        // DataPointer at +0x70.
        put_u64(sys, t_off + 0x70, kGraphicsBase | data_offs[i]);
    }

    // Names blob.
    std::memcpy(sys + names_off, names_blob.data(), names_blob.size());

    // Graphics memory: write each texture's full-mip bytes.
    for (std::size_t i = 0; i < count; ++i) {
        std::memcpy(gfx + data_offs[i],
                    fakes[i].full_data.data(),
                    fakes[i].full_data.size());
    }

    return f;
}

std::vector<std::uint8_t> make_pattern(std::size_t n, std::uint8_t seed) {
    std::vector<std::uint8_t> v(n);
    for (std::size_t i = 0; i < n; ++i) {
        v[i] = static_cast<std::uint8_t>((i * 31u + seed) & 0xffu);
    }
    return v;
}

void test_full_mip_size_vectors() {
    using thorbridge::ytd::full_mip_size;
    CHECK(full_mip_size(64, 64, 1) == 64u * 64u,
          "mip 0 only equals stride * height");
    CHECK(full_mip_size(64, 64, 2) == (64u * 64u + 64u * 64u / 4u),
          "two-level mip chain adds a quarter");
    // 32 * 32 + 32 * 32 / 4 + 32 * 32 / 16 + 32 * 32 / 64
    // = 1024 + 256 + 64 + 16 = 1360
    CHECK(full_mip_size(32, 32, 4) == 1360u,
          "four-level mip chain sums the quartering series");
    CHECK(full_mip_size(0, 64, 3) == 0u,
          "zero stride collapses the mip chain to zero");
    CHECK(full_mip_size(16, 16, 0) == 0u,
          "zero levels means zero mip bytes regardless of stride x height");
}

void test_open_single_texture() {
    FakeTexture fake;
    fake.name      = "test_tile";
    fake.name_hash = 0xDEADBEEFu;
    fake.width     = 128;
    fake.height    = 64;
    fake.depth     = 1;
    fake.stride    = 128;  // DXT1 128x64 would be 2048 bytes; use flat stride for test
    fake.format    = static_cast<std::uint32_t>(thorbridge::ytd::TextureFormat::DXT1);
    fake.levels    = 2;
    // mip 0: stride*height = 128*64 = 8192 bytes
    // mip 1: 8192 / 4         = 2048 bytes
    // full : 10240 bytes
    fake.full_data = make_pattern(10240, 0x7a);
    Fixture f = make_fixture({fake});

    thorbridge::ytd::Dictionary d;
    CHECK(thorbridge::ytd::open(f.payload.data(), f.system_size,
                                 f.graphics_size, d),
          "open() parses a single-texture YTD");
    CHECK(d.textures.size() == 1u, "exactly one texture materialised");
    const auto& t = d.textures[0];
    CHECK(t.name == "test_tile",
          "name resolved via NamePointer -> null-terminated string");
    CHECK(t.name_hash == 0xDEADBEEFu, "name hash matches parallel array");
    CHECK(t.width == 128 && t.height == 64 && t.depth == 1 && t.stride == 128,
          "dimensions preserved verbatim");
    CHECK(t.format == thorbridge::ytd::TextureFormat::DXT1,
          "format parsed as DXT1 (fourcc 'DXT1' LE)");
    CHECK(t.levels == 2, "levels field reads from +0x5D");
    CHECK(t.full_data_size_bytes == 10240u,
          "full-mip byte range sums the mip chain");
    CHECK(t.mip0_size_bytes == 8192u,
          "mip 0 size equals stride * height");
    // The data offset should point at the start of graphics memory,
    // which is `system_size` in the flat payload.
    CHECK(t.full_data_offset_bytes == f.system_size,
          "data offset lands at graphics memory start (flat payload)");
    // Verify the actual pixel bytes resolve correctly.
    CHECK(std::memcmp(f.payload.data() + t.full_data_offset_bytes,
                       fake.full_data.data(), 10240u) == 0,
          "full-mip bytes at the resolved offset match the injected pattern");
}

void test_open_two_textures_and_find() {
    FakeTexture a;
    a.name = "alpha";
    a.name_hash = 1u;
    a.width = 32; a.height = 32; a.depth = 1; a.stride = 32;
    a.format = static_cast<std::uint32_t>(thorbridge::ytd::TextureFormat::DXT5);
    a.levels = 1;
    a.full_data = make_pattern(32 * 32, 0x11);

    FakeTexture b;
    b.name = "Bravo";
    b.name_hash = 2u;
    b.width = 16; b.height = 16; b.depth = 1; b.stride = 16;
    b.format = static_cast<std::uint32_t>(thorbridge::ytd::TextureFormat::DXT1);
    b.levels = 3;
    b.full_data = make_pattern(16 * 16 + 16 * 16 / 4 + 16 * 16 / 16, 0x22);

    Fixture f = make_fixture({a, b});
    thorbridge::ytd::Dictionary d;
    CHECK(thorbridge::ytd::open(f.payload.data(), f.system_size,
                                 f.graphics_size, d),
          "open() parses a two-texture YTD");
    CHECK(d.textures.size() == 2u, "both textures materialised");
    CHECK(d.textures[0].name == "alpha" && d.textures[0].name_hash == 1u,
          "entry 0 holds the first fake");
    CHECK(d.textures[1].name == "Bravo" && d.textures[1].name_hash == 2u,
          "entry 1 holds the second fake");

    const auto* fa = thorbridge::ytd::find(d, "alpha");
    const auto* fb = thorbridge::ytd::find(d, "bravo");  // lower
    const auto* fc = thorbridge::ytd::find(d, "BRAVO");  // upper
    const auto* fm = thorbridge::ytd::find(d, "missing");
    CHECK(fa && fa == &d.textures[0], "find() returns 'alpha'");
    CHECK(fb && fb == &d.textures[1], "find() is case-insensitive (lower)");
    CHECK(fc && fc == &d.textures[1], "find() is case-insensitive (upper)");
    CHECK(fm == nullptr, "find() returns nullptr on miss");

    // Independent pixel ranges.
    CHECK(d.textures[0].full_data_size_bytes == 1024u, "alpha full-mip size");
    CHECK(d.textures[1].full_data_size_bytes == 336u, "bravo full-mip size");
}

void test_open_errors() {
    thorbridge::ytd::Dictionary d;

    // Too-small payload: can't even hold the TextureDictionary.
    std::vector<std::uint8_t> tiny(32, 0);
    CHECK(!thorbridge::ytd::open(tiny.data(), tiny.size(), 0, d),
          "open() refuses payload smaller than the TextureDictionary");

    // Null payload.
    CHECK(!thorbridge::ytd::open(nullptr, 1024, 0, d),
          "open() refuses a null payload");

    // Valid-looking header where the name-hashes pointer points past
    // the end of system memory.
    FakeTexture fake;
    fake.name = "x"; fake.name_hash = 0;
    fake.width = 4; fake.height = 4; fake.depth = 1; fake.stride = 4;
    fake.format = static_cast<std::uint32_t>(thorbridge::ytd::TextureFormat::DXT1);
    fake.levels = 1;
    fake.full_data = make_pattern(16, 0);
    Fixture f = make_fixture({fake});
    // Clobber the TextureNameHashes pointer to way past system memory.
    put_u64(f.payload.data(), 0x20,
            kSystemBase | static_cast<std::uint64_t>(f.system_size + 1));
    CHECK(!thorbridge::ytd::open(f.payload.data(), f.system_size,
                                   f.graphics_size, d),
          "open() refuses an out-of-range name-hashes pointer");
}

void test_open_count_mismatch_refused() {
    FakeTexture fake;
    fake.name = "x"; fake.name_hash = 0;
    fake.width = 4; fake.height = 4; fake.depth = 1; fake.stride = 4;
    fake.format = static_cast<std::uint32_t>(thorbridge::ytd::TextureFormat::DXT1);
    fake.levels = 1;
    fake.full_data = make_pattern(16, 0);
    Fixture f = make_fixture({fake});
    // Set TextureNameHashes count to 2 but Textures count stays at 1.
    put_u16(f.payload.data(), 0x28, 2u);
    thorbridge::ytd::Dictionary d;
    CHECK(!thorbridge::ytd::open(f.payload.data(), f.system_size,
                                   f.graphics_size, d),
          "open() refuses when name-hashes count mismatches textures count");
}

}  // namespace

int main() {
    test_full_mip_size_vectors();
    test_open_single_texture();
    test_open_two_textures_and_find();
    test_open_errors();
    test_open_count_mismatch_refused();
    if (failures) {
        std::fprintf(stderr, "\n%d ytd check(s) failed.\n", failures);
        return 1;
    }
    std::fprintf(stderr, "all ytd checks passed.\n");
    return 0;
}
